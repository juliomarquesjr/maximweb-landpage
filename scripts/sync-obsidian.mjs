#!/usr/bin/env node
import crypto from 'node:crypto';
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(scriptDir, '..');
const knowledgeDir = path.join(rootDir, 'docs', 'knowledge');
const generatedDir = path.join(knowledgeDir, '_generated');

const command = process.argv[2] ?? 'sync';
const generatedRelPaths = [
  'docs/knowledge/_generated/project-map.md',
  'docs/knowledge/_generated/adr-index.md',
  'docs/knowledge/_generated/agent-rules.md',
];

const requiredSources = [
  'AGENTS.md',
  'CLAUDE.md',
  'README.md',
  'docs/ARCHITECTURE.md',
  'docs/DESIGN_TOKENS.md',
  '.github/copilot-instructions.md',
  'package.json',
];

function toPosix(value) {
  return value.split(path.sep).join('/');
}

function fromRoot(relPath) {
  return path.join(rootDir, relPath);
}

async function pathExists(filePath) {
  try {
    await fs.access(filePath);
    return true;
  } catch {
    return false;
  }
}

async function listFiles(relDir, predicate) {
  const absDir = fromRoot(relDir);
  if (!(await pathExists(absDir))) {
    return [];
  }

  const entries = await fs.readdir(absDir, { withFileTypes: true });
  const files = await Promise.all(entries.map(async (entry) => {
    const childRel = toPosix(path.join(relDir, entry.name));
    if (entry.isDirectory()) {
      return listFiles(childRel, predicate);
    }

    return predicate(childRel) ? [childRel] : [];
  }));

  return files.flat().sort((a, b) => a.localeCompare(b));
}

async function readSource(relPath) {
  const absPath = fromRoot(relPath);
  const raw = await fs.readFile(absPath);
  const text = raw.toString('utf8').replace(/\r\n/g, '\n');

  return {
    relPath,
    text,
    hash: crypto.createHash('sha256').update(raw).digest('hex'),
    title: extractTitle(text, relPath),
    headings: extractHeadings(text),
  };
}

function extractTitle(text, relPath) {
  const match = text.match(/^#\s+(.+)$/m);
  return match?.[1]?.trim() ?? path.basename(relPath);
}

function extractHeadings(text) {
  return text
    .split('\n')
    .map((line) => {
      const match = line.match(/^(#{1,3})\s+(.+)$/);
      if (!match) {
        return null;
      }

      return {
        level: match[1].length,
        title: match[2].replace(/\s+#+$/, '').trim(),
      };
    })
    .filter(Boolean);
}

function extractField(text, fieldName) {
  const match = text.match(new RegExp(`\\*\\*${fieldName}:\\*\\*\\s*(.+)`));
  return match?.[1]?.trim() ?? '-';
}

function mdLink(fromRelPath, targetRelPath, label = targetRelPath) {
  const fromAbs = fromRoot(fromRelPath);
  const targetAbs = fromRoot(targetRelPath);
  const href = toPosix(path.relative(path.dirname(fromAbs), targetAbs));
  return `[${label}](${encodeURI(href)})`;
}

function sourceTable(sources, fromRelPath) {
  const rows = sources.map((source) => (
    `| ${mdLink(fromRelPath, source.relPath, source.relPath)} | ${source.title} | \`${source.hash.slice(0, 16)}\` |`
  ));

  return [
    '| Source | Title | SHA-256 |',
    '|---|---|---|',
    ...rows,
  ].join('\n');
}

function generatedBanner() {
  return [
    '<!--',
    'Generated by scripts/sync-obsidian.mjs.',
    'Do not edit this file manually; update the source docs and run npm run knowledge:sync.',
    '-->',
  ].join('\n');
}

function renderHeadingList(source) {
  if (source.headings.length === 0) {
    return '- No markdown headings found.';
  }

  return source.headings.slice(0, 14).map((heading) => {
    const indent = '  '.repeat(Math.max(0, heading.level - 1));
    return `${indent}- ${heading.title}`;
  }).join('\n');
}

async function collectSources() {
  const multiagentSources = await listFiles('docs/multiagentes', (relPath) => relPath.endsWith('.md'));
  const adrSources = await listFiles('adr', (relPath) => relPath.endsWith('.md'));
  const relPaths = [...new Set([
    ...requiredSources,
    ...multiagentSources,
    ...adrSources,
  ])].sort((a, b) => a.localeCompare(b));

  return Promise.all(relPaths.map(readSource));
}

async function collectSrcMap() {
  return listFiles('src', (relPath) => /\.(css|ts|tsx)$/.test(relPath));
}

function renderProjectMap(sources, srcFiles, packageJson) {
  const fromRelPath = 'docs/knowledge/_generated/project-map.md';
  const scripts = Object.entries(packageJson.scripts ?? {})
    .map(([name, value]) => `| \`npm run ${name}\` | \`${value}\` |`)
    .join('\n');

  const dependencies = Object.entries(packageJson.dependencies ?? {})
    .map(([name, version]) => `| \`${name}\` | \`${version}\` |`)
    .join('\n');

  const srcMap = srcFiles.length > 0
    ? srcFiles.map((relPath) => `- ${mdLink(fromRelPath, relPath, relPath)}`).join('\n')
    : '- No source files found.';

  return [
    generatedBanner(),
    '',
    '# Project Map',
    '',
    'This page is a generated navigation layer for the MaximWeb technical memory vault.',
    '',
    '## Package',
    '',
    `- Name: \`${packageJson.name ?? '-'}\``,
    `- Version: \`${packageJson.version ?? '-'}\``,
    `- Private: \`${String(packageJson.private ?? false)}\``,
    '',
    '## Scripts',
    '',
    '| Command | Definition |',
    '|---|---|',
    scripts,
    '',
    '## Runtime Dependencies',
    '',
    '| Package | Version |',
    '|---|---|',
    dependencies,
    '',
    '## Application Source Map',
    '',
    srcMap,
    '',
    '## Knowledge Sources',
    '',
    sourceTable(sources, fromRelPath),
  ].join('\n');
}

function renderAdrIndex(sources) {
  const fromRelPath = 'docs/knowledge/_generated/adr-index.md';
  const adrSources = sources.filter((source) => source.relPath.startsWith('adr/'));
  const rows = adrSources.map((source) => {
    const date = extractField(source.text, 'Data');
    const status = extractField(source.text, 'Status');
    return `| ${mdLink(fromRelPath, source.relPath, source.title)} | ${date} | ${status} | \`${source.hash.slice(0, 16)}\` |`;
  });

  return [
    generatedBanner(),
    '',
    '# ADR Index',
    '',
    'Durable technical decisions live in `adr/`. This generated page indexes them for Obsidian navigation.',
    '',
    '| ADR | Date | Status | SHA-256 |',
    '|---|---|---|---|',
    ...rows,
    '',
    '## Decision Headings',
    '',
    ...adrSources.flatMap((source) => [
      `### ${source.title}`,
      '',
      `Source: ${mdLink(fromRelPath, source.relPath, source.relPath)}`,
      '',
      renderHeadingList(source),
      '',
    ]),
  ].join('\n');
}

function renderAgentRules(sources) {
  const fromRelPath = 'docs/knowledge/_generated/agent-rules.md';
  const agentSourcePaths = new Set([
    'AGENTS.md',
    'CLAUDE.md',
    '.github/copilot-instructions.md',
    'docs/multiagentes/README.md',
    'docs/multiagentes/checklist.md',
  ]);
  const agentSources = sources.filter((source) => agentSourcePaths.has(source.relPath));

  return [
    generatedBanner(),
    '',
    '# Agent Rules',
    '',
    'This page is a generated operational summary for AI agents working on this project.',
    '',
    '## Non-Negotiable Rules',
    '',
    '- Read `AGENTS.md` before code changes.',
    '- For large tasks, also open `docs/knowledge/00-index.md` and this generated page.',
    '- Run `npm run build` after any implementation change.',
    '- Run `npm run knowledge:sync` after structural documentation, durable decisions, or new technical patterns.',
    '- Do not edit files under `docs/knowledge/_generated/` manually.',
    '- Keep durable decisions in `adr/`; the Obsidian vault indexes and summarizes them.',
    '',
    '## Rule Sources',
    '',
    sourceTable(agentSources, fromRelPath),
    '',
    '## Source Headings',
    '',
    ...agentSources.flatMap((source) => [
      `### ${source.title}`,
      '',
      `Source: ${mdLink(fromRelPath, source.relPath, source.relPath)}`,
      '',
      renderHeadingList(source),
      '',
    ]),
  ].join('\n');
}

async function buildOutputs() {
  const sources = await collectSources();
  const srcFiles = await collectSrcMap();
  const packageSource = sources.find((source) => source.relPath === 'package.json');
  const packageJson = JSON.parse(packageSource.text);

  return new Map([
    [generatedRelPaths[0], renderProjectMap(sources, srcFiles, packageJson)],
    [generatedRelPaths[1], renderAdrIndex(sources)],
    [generatedRelPaths[2], renderAgentRules(sources)],
  ]);
}

async function writeIfChanged(relPath, content) {
  const absPath = fromRoot(relPath);
  const normalized = `${content.trimEnd()}\n`;
  let current = null;

  try {
    current = await fs.readFile(absPath, 'utf8');
  } catch {
    // File does not exist yet.
  }

  if (current !== normalized) {
    await fs.writeFile(absPath, normalized, 'utf8');
    return true;
  }

  return false;
}

async function sync() {
  await fs.mkdir(generatedDir, { recursive: true });
  const outputs = await buildOutputs();
  const changed = [];

  for (const [relPath, content] of outputs) {
    if (await writeIfChanged(relPath, content)) {
      changed.push(relPath);
    }
  }

  if (changed.length === 0) {
    console.log('Knowledge vault is already up to date.');
    return;
  }

  console.log('Updated knowledge files:');
  changed.forEach((relPath) => console.log(`- ${relPath}`));
}

async function check() {
  const outputs = await buildOutputs();
  const stale = [];

  for (const [relPath, content] of outputs) {
    const absPath = fromRoot(relPath);
    const expected = `${content.trimEnd()}\n`;
    let current = null;

    try {
      current = await fs.readFile(absPath, 'utf8');
    } catch {
      stale.push(relPath);
      continue;
    }

    if (current !== expected) {
      stale.push(relPath);
    }
  }

  if (stale.length > 0) {
    console.error('Knowledge vault is out of date. Run npm run knowledge:sync.');
    stale.forEach((relPath) => console.error(`- ${relPath}`));
    process.exitCode = 1;
    return;
  }

  console.log('Knowledge vault is up to date.');
}

if (command === 'sync') {
  await sync();
} else if (command === 'check') {
  await check();
} else {
  console.error(`Unknown command: ${command}`);
  console.error('Usage: node scripts/sync-obsidian.mjs [sync|check]');
  process.exitCode = 1;
}
